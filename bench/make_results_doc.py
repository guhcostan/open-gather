def capture(script, *args):
    buf = io.StringIO()
    old = sys.argv
    sys.argv = [script, *args]
    try:
        with contextlib.redirect_stdout(buf):
            runpy.run_path(os.path.join(here, script), run_name="__main__")
    finally:
        sys.argv = old
    return buf.getvalue().strip()

